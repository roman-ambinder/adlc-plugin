'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { paths } = require('./state');
const gates = require('./gates');
const evidence = require('./evidence');
const { packetProblems } = require('./packets');
const { planHash } = require('./exec');

function readDoc(root, name) {
  const f = path.join(paths(root).dir, name);
  return fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '';
}

function acIds(text) {
  return [...new Set([...text.matchAll(/^\s*[-*]\s*(AC-\d+)\s*:/gm)].map((m) => m[1]))];
}

// True when the "## heading" section has at least one line that is not a template hint or comment.
function sectionFilled(text, heading) {
  const lines = text.split('\n');
  const start = lines.findIndex((l) => l.trim() === `## ${heading}`);
  if (start === -1) return false;
  for (let i = start + 1; i < lines.length; i += 1) {
    const l = lines[i].trim();
    if (l.startsWith('## ')) break;
    if (l && !l.startsWith('_') && !l.startsWith('<!--')) return true;
  }
  return false;
}

function trace(root, s) {
  const ev = evidence.list(root);
  return acIds(readDoc(root, 'requirements.md')).map((ac) => {
    const owners = s.tasks.filter((t) => t.ac.includes(ac));
    const files = owners.flatMap((t) => t.checks.map((cmd) => ev.filter((e) => e.cmd === cmd && e.exit === 0).pop()).filter(Boolean).map((e) => e.file));
    const verify = ev.filter((e) => e.stage === 'verify' && e.exit === 0).pop();
    return { ac, tasks: owners.map((t) => ({ id: t.id, status: t.status })), evidence: [...new Set(files)], verify: verify ? verify.file : null };
  });
}

function renderTrace(rows) {
  const lines = ['# Traceability', '', '_Generated by `adlc trace`: acceptance criterion → tasks → passing evidence._', '', '| AC | Tasks | Task evidence (passing) | Latest passing verify run |', '|---|---|---|---|'];
  for (const r of rows) {
    lines.push(`| ${r.ac} | ${r.tasks.map((t) => `${t.id} (${t.status})`).join(', ') || '**none**'} | ${r.evidence.join('<br>') || '**none**'} | ${r.verify || '**none**'} |`);
  }
  return `${lines.join('\n')}\n`;
}

function startProblems(root, s, stage) {
  const p = [];
  if (stage === 'build') {
    if (!s.tasks.length) p.push('no tasks planned');
    const g = gates.check(root, s, 'plan');
    if (!g.ok) p.push(g.reason);
  }
  return p;
}

function completeProblems(root, s, stage) {
  const p = [];
  switch (stage) {
    case 'specify':
      if (!acIds(readDoc(root, 'requirements.md')).length) p.push('requirements.md has no acceptance criteria (add lines like "- AC-1: ...")');
      break;
    case 'plan': {
      const acs = acIds(readDoc(root, 'requirements.md'));
      if (!acs.length) p.push('requirements.md has no acceptance criteria (add lines like "- AC-1: ...")');
      if (!s.tasks.length) p.push('no tasks: add them with `adlc task add --file <json>`');
      for (const t of s.tasks) {
        for (const x of packetProblems(s, t)) p.push(`${t.id}: ${x}`);
        for (const a of t.ac) if (!acs.includes(a)) p.push(`${t.id} references ${a}, which is not in requirements.md`);
      }
      for (const a of acs) if (!s.tasks.some((t) => t.ac.includes(a))) p.push(`${a} is not covered by any task`);
      if (!s.execution.mode) p.push('execution plan not computed: run `adlc exec plan`');
      else if (s.execution.plan_hash !== planHash(s)) p.push('execution plan is out of date: run `adlc exec plan`');
      break;
    }
    case 'build': {
      const open = s.tasks.filter((t) => t.status !== 'integrated');
      if (open.length) p.push(`tasks not integrated: ${open.map((t) => `${t.id} (${t.status})`).join(', ')}`);
      if (s.leases.some((l) => l.status === 'active')) p.push('active worker leases remain');
      break;
    }
    case 'verify': {
      const since = s.stages.verify.started || '';
      const ev = evidence.list(root).filter((e) => e.stage === 'verify' && e.ts >= since);
      if (!ev.length) p.push('no verification evidence since verify started: run checks with `adlc run --stage verify -- "<cmd>"`');
      for (const [cmd, e] of evidence.latestByCmd(ev)) if (e.exit !== 0) p.push(`latest run of "${cmd}" failed (exit ${e.exit}; ${e.file})`);
      break;
    }
    case 'review': {
      const since = s.stages.review.started || '';
      const r = s.reviews.filter((x) => x.ts >= since).pop();
      if (!r) p.push('no review recorded in this stage: `adlc review add --file <md> --blocking N --optional M`');
      else if (r.blocking > 0) p.push(`latest review has ${r.blocking} blocking finding(s); repair the responsible task with \`adlc task repair <T> "<finding>"\``);
      break;
    }
    case 'release': {
      const rel = readDoc(root, 'release.md');
      for (const h of ['Summary of changes', 'Migration', 'Deployment steps', 'Rollback steps']) {
        if (!sectionFilled(rel, h)) p.push(`release.md section "${h}" is empty (write "None." if it does not apply)`);
      }
      for (const row of trace(root, s)) if (!row.evidence.length) p.push(`${row.ac} has no passing task evidence`);
      if (!readDoc(root, 'traceability.md')) p.push('traceability.md missing: run `adlc trace`');
      const g = gates.check(root, s, 'release');
      if (!g.ok) p.push(g.reason);
      break;
    }
    default:
      break;
  }
  return p;
}

module.exports = { acIds, sectionFilled, trace, renderTrace, startProblems, completeProblems, readDoc };
