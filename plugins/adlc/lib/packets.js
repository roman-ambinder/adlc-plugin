'use strict';
const path = require('node:path');
const { paths } = require('./state');
const { atomicWrite } = require('./fsutil');

function packetProblems(s, t) {
  const p = [];
  if (!t.goal) p.push('goal is empty');
  if (!t.files.length) p.push('no writable files');
  if (!t.checks.length) p.push('no task-level checks');
  if (!t.ac.length) p.push('no acceptance criteria referenced');
  for (const c of t.contracts.consumes) if (!s.contracts.some((x) => x.id === c)) p.push(`consumes unknown contract ${c}`);
  for (const c of t.contracts.provides) if (!s.contracts.some((x) => x.id === c)) p.push(`provides unknown contract ${c}`);
  return p;
}

function bullet(items, empty = 'none') {
  return items.length ? items.map((x) => `- ${x}`).join('\n') : `- ${empty}`;
}

const WORKSPACE = {
  sequential: 'Work in the main checkout. No other worker is running.',
  shared: 'Work in the main checkout. Other workers edit other files at the same time: touch only your writable files.',
  worktree: 'Work in your isolated git worktree (your current directory). Do not commit; the coordinator integrates.',
};

function renderPacket(s, t) {
  const contract = (id) => {
    const c = s.contracts.find((x) => x.id === id);
    if (!c) return `${id} (missing)`;
    return `${c.id} — ${c.title}\n\n  \`\`\`\n  ${c.spec.split('\n').join('\n  ')}\n  \`\`\``;
  };
  const handoff = {
    task: t.id, status: 'done | blocked | partial', workspace: '<absolute path of your working directory>', branch: null,
    files_changed: [], summary: '', checks: [{ cmd: '<exact check command>', exit: 0, evidence: '<file printed by adlc run>' }],
    interface_changes: [], blockers: [], integration_notes: '', out_of_scope: [],
  };
  return [
    `# Build packet ${t.id}: ${t.title}`,
    '',
    `Change: ${s.change.id}. Generated by \`adlc packet render\` from state.json — do not edit; change the plan instead.`,
    '',
    '## Goal',
    t.goal,
    '',
    '## Acceptance criteria covered',
    bullet(t.ac),
    '',
    '## Prerequisites',
    bullet([...t.deps.map((d) => `task ${d} (integrated)`), ...t.contracts.consumes.map((c) => `contract ${c}`)]),
    '',
    '## Writable files (only these)',
    bullet(t.files),
    '',
    '## Read-only context',
    bullet(t.reads),
    '',
    '## Interfaces provided',
    bullet(t.contracts.provides.map(contract)),
    '',
    '## Interfaces consumed',
    bullet(t.contracts.consumes.map(contract)),
    '',
    '## Task-level checks',
    `Run each with \`adlc run --stage build --task ${t.id} -- "<command>"\`:`,
    bullet(t.checks.map((c) => `\`${c}\``)),
    '',
    '## Resources',
    bullet(t.resources),
    '',
    '## Size and attempts',
    `- size: ${t.size}${t.coupled ? ' (coupled: runs alone)' : ''}`,
    `- attempt ${t.attempts + 1} of ${t.max_attempts}`,
    ...(t.last_failure ? [`- previous attempt failed: ${t.last_failure}`] : []),
    '',
    '## Workspace',
    WORKSPACE[s.execution.mode] || WORKSPACE.sequential,
    '',
    '## Done when',
    '- every task-level check passes when run through `adlc run`',
    '- only the writable files above changed',
    `- a handoff was submitted with \`adlc worker handoff ${t.id} --file <path>\``,
    '',
    '## Handoff JSON',
    '```json',
    JSON.stringify(handoff, null, 2),
    '```',
    '',
  ].join('\n');
}

function packetPath(root, id) {
  return path.join(paths(root).packets, `${id}.md`);
}

function writePackets(root, s, ids) {
  const out = [];
  for (const t of s.tasks) {
    if (ids && !ids.includes(t.id)) continue;
    const f = packetPath(root, t.id);
    atomicWrite(f, renderPacket(s, t), paths(root).tmp);
    out.push(f);
  }
  return out;
}

module.exports = { packetProblems, renderPacket, packetPath, writePackets };
